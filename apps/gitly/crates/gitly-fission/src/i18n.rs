fn bundle<const N: usize>(locale: &str, messages: [(&str, &str); N]) -> TranslationBundle {
    TranslationBundle {
        locale: Locale::from(locale),
        messages: messages
            .into_iter()
            .map(|(key, value)| (key.to_string(), value.to_string()))
            .collect::<HashMap<_, _>>(),
    }
}
